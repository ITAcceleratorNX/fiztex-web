import { QRCodeSVG } from 'qrcode.react';

interface QrPosterProps {
  /** Строка из ответа бэкенда — рисуется как есть, разбирать её клиенту нечего. */
  payload: string;
}

/**
 * QR-код для класса.
 *
 * <b>Размер — единственная величина этого экрана вне токенов, и он физический:</b> код
 * читают с задней парты, а не с рабочего места. Отсюда «занять почти весь экран», но с
 * двумя оговорками, вторая найдена на живом экране:
 *
 * <ul>
 *   <li>ширина ограничена 70vw, чтобы код не упирался в короткую сторону экрана;</li>
 *   <li>из высоты вычитается обвязка карточки (~260 px: шапка, подпись классу, кнопки и
 *       отступы). Без этого на невысоком окне кнопка «Закрыть» уезжает за нижний край, и
 *       учитель остаётся с кодом, из которого не выйти мышью.</li>
 * </ul>
 *
 * <b>Уровень коррекции M.</b> Больше коррекции — плотнее модули и хуже читается издалека,
 * меньше — нет запаса на блик от проектора. Если в классе не сканируется, первым делом
 * пробовать `L`.
 *
 * Ни логотипа, ни рамки поверх кода: всё это съедает контраст на дистанции.
 */
export function QrPoster({ payload }: QrPosterProps) {
  return (
    <div
      className="mx-auto"
      style={{ width: 'clamp(180px, min(100vh - 260px, 70vw), 560px)' }}
    >
      <QRCodeSVG
        value={payload}
        level="M"
        // Атрибут нужен qrcode.react для расчёта viewBox; настоящий размер задаёт CSS.
        size={512}
        marginSize={2}
        className="h-auto w-full"
        role="img"
        aria-label="QR-код для отметки посещаемости"
      />
    </div>
  );
}
