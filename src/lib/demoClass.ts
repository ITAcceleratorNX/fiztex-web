/**
 * Тестовый (DEMO) класс — пилот, пункт 4.3: рядом с настоящим 8S его легко перепутать.
 *
 * <p>Признак приходит с сервера флагом класса (`demo` / `classDemo`), а не угадывается по
 * имени: имя участвует в поиске, импорте и отчётах, и метка внутри него ломала бы
 * сопоставление. Здесь только то, как флаг показать.
 */
export const DEMO_MARK = 'DEMO';

/** Для мест, где у класса только строка: пункт выпадающего списка, подпись. */
export function withDemoMark(name: string, demo: boolean | undefined): string {
  return demo ? `${name} · ${DEMO_MARK}` : name;
}
