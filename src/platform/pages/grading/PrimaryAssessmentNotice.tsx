import { NoticeBar } from '@/components/ui/NoticeBar';

/** Применимость правил; расчёт и допустимые работы определяет сервер листа урока. */
export function PrimaryAssessmentNotice({ startDate, active }: { startDate?: string; active: boolean }) {
  if (!startDate) return null;
  if (startDate < '2026-09-01') {
    return (
      <NoticeBar>
        Правила начальной школы с сентября 2026 года к этому учебному году не применяются.
        Исторические оценки сохраняют прежний порядок расчёта. В 1 классе оценки не выставляются.
      </NoticeBar>
    );
  }

  return (
    <NoticeBar tone={active ? 'soft' : 'warning'}>
      <strong className="block">2–4 классы: ФО 50% + промежуточное оценивание (ПО) 50%</strong>
      <span className="mt-1 block">
        {active
          ? 'В периодах, для которых утверждена политика, журнал автоматически рассчитывает результат по этим правилам. '
          : 'Для запуска расчёта утвердите политику этого учебного года. '}
        Отдельный шаблон для начальной школы выбирать не нужно. Максимум ПО: 2 класс — 12,
        3 класс — 14, 4 класс — 16. ФО — единый балл за урок от 1 до 10 с учётом домашней работы.
        Отдельный СОЧ не проводится. Без результатов ПО четвертный итог не выставляется.
      </span>
      <span className="mt-1 block">
        При ФО оценивайте каждого ученика по каждому предмету не менее чем на 30% проведённых
        уроков, охватывая не менее 50% учебных целей. Письменные работы ПО храните до конца
        учебного года.
      </span>
      <span className="mt-1 block">
        Эти правила действуют по всем предметам 2–4 классов, включая физкультуру и музыку.
        В 1 классе оценки не выставляются. Схема ФО 25% + СОР 25% + СОЧ 50% и зачётные
        предметы относятся к 5–11 (12) классам.
      </span>
      <a
        className="mt-2 inline-block underline underline-offset-2"
        href="https://old.adilet.zan.kz/rus/docs/V2600039896"
        target="_blank"
        rel="noreferrer"
      >
        Правила РК с 1 сентября 2026 года, глава 1-1
      </a>
    </NoticeBar>
  );
}
